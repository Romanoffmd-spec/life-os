export function phaseFor(week) { return PHASES.find(p => week >= p.weeks[0] && week <= p.weeks[1]) || PHASES[2]; }

/** Сессия A/B/C для заданной недели программы и места тренировок ('gym' | 'home') */
export function session(letter, week, place = 'gym') {
  const ph = phaseFor(week); const v = k => ({ name: EX[k][place === 'home' ? 'home' : 'gym'], cue: EX[k].cue });
  const strength = (keys, core) => [
    ...keys.map(k => ({ ...v(k), sets: ph.sets, reps: ph.reps })),
    { ...v(core[0]), sets: ph.sets, reps: week <= 4 ? '20-30 с' : week <= 8 ? '30-40 с' : '40-60 с' },
    { ...v(core[1]), sets: 2, reps: '8-10 на сторону' }
  ];
  if (letter === 'A') return { letter, title: 'Тренировка A: всё тело', minutes: 40, warmup: '5 минут: ходьба или велотренажёр, затем 1 лёгкий подход первого упражнения', items: strength(['squat', 'pulldown', 'bench', 'rdl'], ['plank', 'deadbug']), phase: ph };
  if (letter === 'B') return { letter, title: 'Тренировка B: всё тело', minutes: 40, warmup: '5 минут: ходьба или велотренажёр, затем 1 лёгкий подход первого упражнения', items: strength(['legpress', 'row', 'ohp', 'bridge'], ['sideplank', 'deadbug']), phase: ph };
  return { letter: 'C', title: 'Тренировка C: кардио и кор', minutes: ph.cardio + 10, warmup: '5 минут спокойного темпа',
    items: [{ name: `Ходьба в горку, велотренажёр или эллипс: ${ph.cardio} мин в зоне 2`, cue: 'Можешь говорить предложениями, но не петь. По часам: около 60-70% от максимального пульса', sets: 1, reps: `${ph.cardio} мин` },
      { ...v('plank'), sets: 2, reps: '30-45 с' }, { ...v('sideplank'), sets: 2, reps: '20-30 с на сторону' }], phase: ph };
}

