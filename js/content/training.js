/** Целевые шаги: от текущего среднего +1000 каждые 2 недели до цели */
export function stepsTarget(baseline, week, goal = 9000) {
  const start = Math.max(5000, Math.round((baseline || 6000) / 500) * 500);
  return Math.min(Math.max(goal, start), start + Math.floor((week - 1) / 2) * 1000);
}
